def get_schema(): 
    return """ 
    Table: employees 
    Columns: 
    - id (INTEGER PRIMARY KEY) 
    - name (TEXT) 
    - department (TEXT) 
    - salary (REAL) 
 
    Table: departments 
    Columns: 
    - id (INTEGER PRIMARY KEY) 
    - name (TEXT) 
    - budget (REAL) 
    """ 

# p.esguerra: This function explicitly flags non-SELECT queries and raises an error
def validate_sql(sql): 
    # Basic safety checks 
    sql_lower = sql.lower() 
    if any(word in sql_lower for word in ['drop', 'delete', 'update', 'insert']): 
        raise ValueError("Only SELECT queries are allowed") 
    return sql 
 
def execute_query(sql): 
    sql = validate_sql(sql) 
    conn = sqlite3.connect('company.db') 
    try: 
        cursor = conn.cursor() 
        cursor.execute(sql) 
        results = cursor.fetchall() 
        return results 
    except Exception as e: 
        return f"Error: {str(e)}" 
    finally: 
        conn.close() 
 
def format_results(results): 
    if not isinstance(results, list): 
        return str(results) 
    if not results: 
        return "No results found" 
     
    # If it's a single column result 
    if len(results[0]) == 1: 
        return "\n".join([str(row[0]) for row in results]) 
     
    # For multiple columns, try to format as a table 
    # Get column names from the first result 
    if isinstance(results[0], tuple): 
        # Format each row with proper spacing 
        formatted_rows = [] 
        for row in results: 
            row_items = [] 
            for item in row: 
                if isinstance(item, float): 
                    row_items.append(f"${item:,.2f}" if "salary" in str(row) or "budget" in str(row) else f"{item:.2f}") 
                else: 
                    row_items.append(str(item)) 
            formatted_rows.append("\t".join(row_items)) 
        return "\n".join(formatted_rows) 
     
    return "\n".join([str(row) for row in results]) 

# p.esguerra: In the original code, we can maybe set an additional instruction in the system prompt to avoid
# generating non-SELECT queries. But for safety, we also validate the SQL before executing it
def generate_sql(question): 
    response = openai.ChatCompletion.create( 
        model="gpt-4", # p.esguerra: Use gpt-4o-mini supports structure output, however openai 0.28.0 does not
        messages=[ 
            {"role": "system", "content": f"""You are a SQL expert. Use this schema:\n{get_schema()} 
            Return ONLY the SQL query without any explanation or markdown formatting.
            Do not return any non-SELECT queries like DROP, DELETE, UPDATE, INSERT,
            if the user asks for it, apologies and explain that only reading data are allowed."""}, 
            {"role": "user", "content": f"Generate SQL for: {question}"} 
        ],
        functions=[
            {
                "name": "set_response",
                "description": "Provide response in structured format and whether the SQL is generated or not",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "sql_query": {"type": "string", "description": "The SQL query"},
                        "is_generated": {"type": "boolean", "description": "Whether the SQL was generated by the model"},
                        "message": {"type": "string", "description": "Message if SQL was not generated" }
                    },
                    "required": ["sql_query", "is_generated"]
                }
            }
        ],
        function_call={"name": "set_response"} #p.esguerra: force to use the function
    )
    
    function_call = response.choices[0].message.function_call
    
    return json.loads(function_call.arguments)

def query_agent(question): 
    try: 
        # Generate SQL 
        response = generate_sql(question)
        
        # p.esguerra: There should be a better way to check if the LLM refused to generate SQL
        #       perhaps by using structured output or function calling
        #       Since we're limited to the version of openai package, we'll do a simple check here
        # if "sorry" not in response.lower() or "error" not in response.lower():
        #     return response
    
        # p.esguerra: Check if SQL was generated and instead use the message property
        if not response.get("is_generated", False):
            return response.get("message", "The model did not generate a SQL query.")
    
        sql = response.get("sql_query")

        # Remove any markdown code block syntax 
        sql = sql.replace('```sql', '').replace('```SQL', '').replace('```', '') 

        # Remove any explanatory text before or after the SQL 
        sql_lines = [line.strip() for line in sql.split('\n') if line.strip()] 
        sql = ' '.join(sql_lines) 
        
        print(f"Generated SQL: {sql}\n") 
         
        # Execute and format results 
        results = execute_query(sql) 
        return format_results(results) 
    except Exception as e: 
        return f"Error: {str(e)}" 
 
